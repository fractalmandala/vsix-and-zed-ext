'use strict';

const path = require('node:path');
const os = require('node:os');

const THEME_TYPES = {
  light: 'vs',
  dark: 'vs-dark',
  hcLight: 'hc-light',
  hcDark: 'hc-black',
  'hc-black': 'hc-black',
  'hc-light': 'hc-light'
};

const BASE_ENGINE = '^1.60.0';

function slugify(value) {
  return String(value || '')
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

function uiThemeFor(themeType) {
  return THEME_TYPES[themeType] || 'vs-dark';
}

function themeFileName(label) {
  return `${slugify(label) || 'theme'}-color-theme.json`;
}

function parseThemeText(text) {
  const theme = JSON.parse(text);

  if (!theme || typeof theme !== 'object') {
    throw new Error('Theme JSON must contain an object.');
  }

  return theme;
}

/**
 * Rename a theme document without disturbing anything else. The name is written
 * by replacing the existing `name` value in place when there is one, so key
 * order and formatting survive; otherwise it is added as the first key.
 */
function withName(text, name) {
  const namePattern = /("name"\s*:\s*")((?:[^"\\]|\\.)*)(")/;

  if (namePattern.test(text)) {
    return text.replace(namePattern, (_match, prefix, _old, suffix) => `${prefix}${name}${suffix}`);
  }

  const openingBrace = text.indexOf('{');
  if (openingBrace === -1) {
    throw new Error('Theme JSON has no object to name.');
  }

  const rest = text.slice(openingBrace + 1);

  if (rest.trimStart().startsWith('}')) {
    return `${text.slice(0, openingBrace + 1)}\n  "name": ${JSON.stringify(name)}\n${rest}`;
  }

  return `${text.slice(0, openingBrace + 1)}\n  "name": ${JSON.stringify(name)},${rest}`;
}

/**
 * The manifest for a theme-only extension, so the exported colors can be picked
 * up by the Color Theme picker.
 */
function buildThemeExtensionManifest({ label, themeType, themeFileName: fileName, version = '1.0.0', publisher = 'fractal-theme-studio' }) {
  const name = slugify(label) || 'generated-theme';

  return {
    name,
    displayName: label,
    description: `Generated by Fractal Theme Studio from ${label}.`,
    version,
    publisher,
    license: 'MIT',
    engines: { vscode: BASE_ENGINE },
    categories: ['Themes'],
    contributes: {
      themes: [
        {
          label,
          uiTheme: uiThemeFor(themeType),
          path: `./themes/${fileName}`
        }
      ]
    }
  };
}

function extensionDirectoryName(manifest) {
  return `${manifest.publisher}.${manifest.name}-${manifest.version}`;
}

function extensionsRoot(homedir = os.homedir()) {
  return path.join(homedir, '.vscode', 'extensions');
}

function buildInstallTarget({ manifest, homedir = os.homedir() }) {
  const directory = path.join(extensionsRoot(homedir), extensionDirectoryName(manifest));

  return {
    directory,
    packageJsonPath: path.join(directory, 'package.json'),
    themePath: path.join(directory, 'themes', manifest.contributes.themes[0].path.replace('./themes/', ''))
  };
}

module.exports = {
  BASE_ENGINE,
  buildInstallTarget,
  buildThemeExtensionManifest,
  extensionDirectoryName,
  extensionsRoot,
  parseThemeText,
  slugify,
  themeFileName,
  uiThemeFor,
  withName
};
